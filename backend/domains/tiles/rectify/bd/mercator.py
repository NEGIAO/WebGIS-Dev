def _poly6(row, abs_v: float) -> float:
    """官方 gK 多项式：d = |v|/row[9] 代入 row[2..8] 六阶多项式。

    Args:
        row: 当前分带的 10 元系数行
        abs_v: |lat|（LL2MC）或 |mercator_y|（MC2LL）

    Returns:
        多项式求值结果
    """
    d = abs_v / row[9]
    return (
        row[2] + row[3] * d + row[4] * d**2 + row[5] * d**3
        + row[6] * d**4 + row[7] * d**5 + row[8] * d**6
    )


def bd_ll2mc(lon: float, lat: float) -> Tuple[float, float]:
    """BD-09 经纬度 → 百度平面坐标（米），官方 LL2MC 分段多项式。

    Args:
        lon: BD-09 经度
        lat: BD-09 纬度

    Returns:
        (x, y) 百度平面坐标（米），原点 (0,0)，y 向北为正
    """
    abs_lat = abs(lat)
    row = next((_LL2MC[i] for i, b in enumerate(_LL_BANDS) if abs_lat >= b), None)
    if row is None:
        # 南半球补丁：官方 Eb() 对 lat < -75 不选带为已确认 bug（2016 官方确认）
        row = next((_LL2MC[i] for i, b in enumerate(_LL_BANDS) if abs_lat <= -b), _LL2MC[-1])
    c = row[0] + row[1] * abs(lon)
    d = _poly6(row, abs_lat)
    return (c if lon >= 0 else -c), (d if lat >= 0 else -d)


def bd_mc2ll(x: float, y: float) -> Tuple[float, float]:
    """百度平面坐标（米）→ BD-09 经纬度，官方 MC2LL 分段多项式。

    Args:
        x: 百度平面坐标 x（米）
        y: 百度平面坐标 y（米）

    Returns:
        (lon, lat) BD-09 经纬度
    """
    abs_y = abs(y)
    row = next((_MC2LL[i] for i, b in enumerate(_MC_BANDS) if abs_y >= b), _MC2LL[-1])
    c = row[0] + row[1] * abs(x)
    d = _poly6(row, abs_y)
    return (c if x >= 0 else -c), (d if y >= 0 else -d)


def bd_res(z: int) -> float:
    """百度瓦片地面分辨率 (m/px)：res(z) = 2^(18-z)。"""
    return float(2 ** (18 - z))


def bd_lonlat_to_px(lon: float, lat: float, z: int) -> Tuple[float, float]:
    """BD-09 经纬度 → 该层级下百度全局像素坐标（Y 轴向上）。

    Args:
        lon: BD-09 经度
        lat: BD-09 纬度
        z: 百度层级

    Returns:
        (px, py) 全局像素坐标，py 向北增大
    """
    mx, my = bd_ll2mc(lon, lat)
    return mx / bd_res(z), my / bd_res(z)


def bd_lonlat_to_tile_px(lon: float, lat: float, z: int) -> Tuple[int, int, float, float]:
    """BD-09 经纬度 → 百度瓦片索引与瓦片内像素偏移。

    Args:
        lon: BD-09 经度
        lat: BD-09 纬度
        z: 百度层级

    Returns:
        (tx, ty, offset_x, offset_y_from_top)——offset 以瓦片左上角为原点
        （百度 py 向北增大、瓦片顶部对应大 py，故 from_top = (ty+1)*256 - py）
    """
    px, py = bd_lonlat_to_px(lon, lat, z)
    tx, ty = math.floor(px / TILE_SIZE), math.floor(py / TILE_SIZE)
    return tx, ty, px - tx * TILE_SIZE, (ty + 1) * TILE_SIZE - py


def bd_tile_bbox(tx: int, ty: int, z: int) -> Tuple[Tuple[float, float], Tuple[float, float]]:
    """百度瓦片索引 → BD-09 经纬度 bbox。

    Args:
        tx: 百度瓦片 x 索引
        ty: 百度瓦片 y 索引
        z: 百度层级

    Returns:
        ((lt_lon, lt_lat), (rb_lon, rb_lat)) 左上角 / 右下角 BD-09 经纬度
    """
    res = bd_res(z)
    lt = bd_mc2ll(tx * TILE_SIZE * res, (ty + 1) * TILE_SIZE * res)
    rb = bd_mc2ll((tx + 1) * TILE_SIZE * res, ty * TILE_SIZE * res)
    return lt, rb